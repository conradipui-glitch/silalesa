import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const seoData = [
  'seo-pages.json',
  'seo-page-guides.json',
  'seo-page-guides-remont.json',
  'seo-page-guides-screed.json',
  'seo-page-guides-plaster.json',
  'seo-page-guides-materials.json',
];
const overrideData = [
  'seo-page-overrides.json',
  'seo-page-overrides-next.json',
  'seo-page-overrides-r3.json',
  'seo-page-overrides-r4.json',
  'seo-page-overrides-r5.json',
  'seo-page-overrides-r6.json',
  'seo-page-overrides-r7.json',
];
const read = async (name) => JSON.parse(await fs.readFile(path.join(root, 'src/data', name), 'utf8'));
const originals = (await Promise.all(seoData.map(read))).flat();
const overrides = (await Promise.all(overrideData.map(read))).flat();
const overrideMap = new Map();
for (const override of overrides) overrideMap.set(override.slug, {...overrideMap.get(override.slug), ...override});
const pages = originals.map(page => ({...page, ...overrideMap.get(page.slug)}));
const slugs = pages.map(page => page.slug);
if (slugs.length !== new Set(slugs).size) throw new Error('Duplicate canonical SEO slugs');
const productLandingById = {};
for (const page of pages) if (page.productId) {
  if (productLandingById[page.productId]) throw new Error(`Duplicate product landing: ${page.productId}`);
  productLandingById[page.productId] = page.slug;
}
const content = [
  '// AUTO-GENERATED by scripts/generate-route-manifest.mjs. Do not hand-edit.',
  '// Only routing keys are in the initial JS; full SEO content loads on relevant routes.',
  `export const seoSlugs: string[] = ${JSON.stringify(slugs, null, 2)};`,
  `export const productLandingById: Record<string, string> = ${JSON.stringify(productLandingById, null, 2)};`,
  '',
].join('\n');
const output = path.join(root, 'src/data/routeManifest.ts');
if (process.argv.includes('--write')) {
  await fs.writeFile(output, content);
  console.log(`ROUTE MANIFEST GENERATED: ${slugs.length} slugs, ${Object.keys(productLandingById).length} product URLs`);
} else {
  const actual = await fs.readFile(output, 'utf8');
  if (actual !== content) throw new Error('Route manifest outdated: run node scripts/generate-route-manifest.mjs --write');
  console.log(`ROUTE MANIFEST PASS: ${slugs.length} slugs, ${Object.keys(productLandingById).length} product URLs`);
}
